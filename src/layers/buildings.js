import * as THREE from 'three';
import { GeometryBatch } from '../graphics/batch.js';
import { extrudePolygon, hipRoof, insetRoof, m4, scaleUV } from '../graphics/geometry.js';
import { coneRoof, facadeWalls, parapet, posts, tieredRoof } from '../graphics/architecture.js';
import { materials } from '../graphics/materials.js';
import { releaseStatic } from '../graphics/memory.js';

const ROOF_MATERIAL = { tile: 'tile', thatch: 'thatch', white: 'white', stone: 'stone', slate: 'slate' };
/**
 * Tile-roofed buildings are colonial (hacienda, pueblo): plaster painted cream,
 * ochre or maroon like the ones around the Capilla de Guadalupe. Picked from the
 * OSM id so it never changes between builds.
 */
const COLONIAL_FACADES = ['facade', 'facadeOchre', 'facadeMaroon'];

/**
 * Generic buildings generated by the pipeline (buildings.json):
 *  - src 'osm':  OpenStreetMap footprints with facade walls and a roof whose
 *                type/color was read from the illustration
 *  - src 'blob': palapas and sunshades detected on the illustration
 * All of it is merged into one mesh per material.
 * @returns {import('./index.js').Layer}
 */
export function createBuildingsLayer({ buildings: list }) {
  const batch = new GeometryBatch();
  for (const b of list) {
    const { box } = b;
    if (b.src === 'osm') {
      const base = b.y - 1.2;
      const wallMat = b.roof === 'white' ? 'white' : 'wall';
      const facadeMat = b.roof === 'white' ? 'facadeWhite' : b.roof === 'tile' ? COLONIAL_FACADES[b.id % 3] : 'facade';
      const walls = facadeWalls(b.poly, base, b.wall + 1.2);
      batch.add(facadeMat, walls);
      if (b.shape === 'flat') {
        batch.add(wallMat, extrudePolygon(b.poly, 0.01, { top: true }), m4(0, b.y + b.wall - 0.01, 0));
        for (const [g, mm] of parapet(b.poly, b.y + b.wall)) batch.add(wallMat, g, mm);
      }
      if (b.shape === 'inset') {
        const pitch = b.roof === 'thatch' ? 0.62 : 0.4;
        const inset = Math.min(6, Math.min(box.length, box.width) * 0.32);
        batch.add(ROOF_MATERIAL[b.roof], insetRoof(b.poly, inset, inset * pitch, 0.7), m4(0, b.y + b.wall, 0));
      } else if (b.shape === 'hip') {
        const pitch = b.roof === 'thatch' ? 0.62 : 0.38;
        const h = Math.min(box.length, box.width) * pitch;
        batch.add(ROOF_MATERIAL[b.roof], hipRoof(box.length, box.width, Math.min(h, 9), 0.7), m4(box.cx, b.y + b.wall, box.cz, -box.angle));
      } else {
        const roof = extrudePolygon(b.poly, 0.35, { top: true });
        batch.add(ROOF_MATERIAL[b.roof] ?? 'stone', roof, m4(0, b.y + b.wall - 0.2, 0));
      }
      continue;
    }
    // palapas & umbrellas from the illustration
    const y = Math.max(b.y, 0.3);
    if (b.shape === 'cone' || b.kind === 'umbrella') {
      const r = Math.max(box.length, box.width) / 2 + 0.4;
      const h = Math.min(18, Math.max(1.6, r * 0.95));
      if (b.kind === 'umbrella') {
        const pole = new THREE.CylinderGeometry(0.08, 0.08, b.wall, 4);
        pole.translate(0, b.wall / 2, 0);
        batch.add('wood', pole, m4(box.cx, y, box.cz));
      } else {
        const n = Math.max(5, Math.min(16, Math.round(r * 1.4)));
        const post = new THREE.CylinderGeometry(0.16, 0.18, b.wall, 5);
        post.translate(0, b.wall / 2, 0);
        for (let i = 0; i < n; i++) {
          const a = (i / n) * Math.PI * 2;
          batch.add('wood', post.clone(), m4(box.cx + Math.cos(a) * r * 0.82, y, box.cz + Math.sin(a) * r * 0.82));
        }
        if (r > 8)
          batch.add(
            'wood',
            scaleUV(new THREE.CylinderGeometry(r * 0.15, r * 0.18, b.wall + h * 0.5, 8), 0.3),
            m4(box.cx, y + (b.wall + h * 0.5) / 2, box.cz),
          );
      }
      if (r > 6) tieredRoof(batch, box.cx, y + b.wall, box.cz, r, h);
      else batch.add('thatch', coneRoof(r, h), m4(box.cx, y + b.wall, box.cz));
    } else {
      const h = Math.min(box.length, box.width) * 0.58;
      posts(batch, box.cx, y, box.cz, box.length * 0.9, box.width * 0.9, box.angle, b.wall);
      batch.add(
        b.roof === 'tile' ? 'tile' : 'thatch',
        hipRoof(box.length, box.width, Math.min(h, 10), 0.5),
        m4(box.cx, y + b.wall, box.cz, -box.angle),
      );
    }
  }
  const object = releaseStatic(batch.build(materials()));
  object.name = 'buildings';
  return { name: 'buildings', object, occludesRoutes: true };
}
